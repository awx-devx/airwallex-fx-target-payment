import { writeFile } from 'node:fs/promises';
import path from 'node:path';

export type CheckStatus = 'pass' | 'fail' | 'blocked' | 'recorded';

export interface CheckResult {
  id: string;
  status: CheckStatus;
  detail: string;
}

const BLOCKING = new Set(['V1', 'V2', 'V4', 'V5', 'V8', 'V9']);

export function blockingFailed(checks: CheckResult[]): CheckResult[] {
  return checks.filter((check) => BLOCKING.has(check.id) && check.status !== 'pass');
}

export function renderResults(input: {
  ranAt: string;
  notes: string[];
  checks: CheckResult[];
}): string {
  const rows = input.checks
    .map((check) => `| ${check.id} | ${check.status} | ${cell(check.detail)} |`)
    .join('\n');
  const notes = input.notes.map((note) => `- ${note}`).join('\n');
  return `# Airwallex sandbox verification

Ran at ${input.ranAt}. Generated by \`pnpm airwallex:smoke\` and \`pnpm seed:beneficiaries\`.

| ID | Result | Detail |
| --- | --- | --- |
${rows}

## Notes

${notes || '- none'}
`;
}

export async function writeResults(markdown: string): Promise<void> {
  await writeFile(path.resolve(process.cwd(), 'docs/verification-results.md'), markdown);
}

function cell(value: string): string {
  return value.replace(/\|/g, '/').replace(/\s+/g, ' ').trim();
}
